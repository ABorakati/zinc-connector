// zotero-next fork: writes src/browserExt/updateKey.js, the PUBLIC key that verifies the update feed (latest-extension.json,
// signed by zotero-next's gpui-ui/scripts/release.ts). The extension (src/browserExt/updateNotice.js) reads self.ZINC_UPDATE_PUBKEY.
//
//   bun scripts/gen-update-key.ts [<path to update-pubkey.txt>]
//
// Where the key comes from, first hit wins: the path argument, ZN_UPDATE_PUBKEY (the key itself), ZN_UPDATE_PUBKEY_FILE (a file with it),
// ../zotero-next/gpui-ui/update-pubkey.txt next to this checkout (the file zotero-next commits). It is the raw 32-byte Ed25519 public key,
// base64. Nothing found: the file is still written, with an empty key, and the built extension never shows an update notice.
// Run it before build-win.ts copies src/browserExt (the file is not committed: see .gitignore). Never put a private key here.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const OUT = join(resolve(import.meta.dir, ".."), "src", "browserExt", "updateKey.js");

export function readPublicKey(arg?: string): string {
	const sibling = resolve(import.meta.dir, "..", "..", "zotero-next", "gpui-ui", "update-pubkey.txt");
	const raw = (arg ? readFileSync(arg, "utf8")
		: process.env.ZN_UPDATE_PUBKEY ?? (process.env.ZN_UPDATE_PUBKEY_FILE ? readFileSync(process.env.ZN_UPDATE_PUBKEY_FILE, "utf8") : existsSync(sibling) ? readFileSync(sibling, "utf8") : "")).trim();
	if (raw && Buffer.from(raw, "base64").length !== 32) throw new Error("the update public key is not a base64 32-byte Ed25519 key");
	return raw;
}

if (import.meta.main) {
	const key = readPublicKey(process.argv[2]);
	writeFileSync(OUT, `// generated by scripts/gen-update-key.ts: do not edit, do not commit\nself.ZINC_UPDATE_PUBKEY = ${JSON.stringify(key)};\n`);
	console.log(key ? `updateKey.js: update public key ${key}` : "updateKey.js: no update public key found (ZN_UPDATE_PUBKEY / ZN_UPDATE_PUBKEY_FILE / ../zotero-next/gpui-ui/update-pubkey.txt): this build shows no update notice");
}
